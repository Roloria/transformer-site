/* ===========================================================
   Language switching engine
   =========================================================== */
(function() {
  const defs = window.I18N_DEF;
  let current = 'en';

  // Get translation for key, falling back to EN then the key itself
  window.T = function(key) {
    const table = defs[current] || defs.en;
    if (key in table) return table[key];
    if (key in defs.en) return defs.en[key];
    return key;
  };
  window.getLang = function() { return current; };

  function applyLang(lang) {
    if (lang !== 'zh' && lang !== 'en') lang = 'en';
    current = lang;
    document.documentElement.lang = lang;
    document.documentElement.setAttribute('data-current-lang', lang);

    // Static elements
    document.querySelectorAll('[data-i18n]').forEach(function(el) {
      const key = el.getAttribute('data-i18n');
      const val = window.T(key);
      if (val != null) el.innerHTML = val;
    });

    // Language buttons
    document.querySelectorAll('.lang-btn').forEach(function(btn) {
      btn.classList.toggle('is-active', btn.getAttribute('data-lang') === lang);
    });

    // Notify dynamic renderers
    window.dispatchEvent(new CustomEvent('langchange', { detail: { lang: lang } }));

    try { localStorage.setItem('tf-lang', lang); } catch (e) {}
  }
  window.applyLang = applyLang;

  // Wire buttons
  document.querySelectorAll('.lang-btn').forEach(function(btn) {
    btn.addEventListener('click', function() {
      applyLang(btn.getAttribute('data-lang'));
    });
  });

  // Init from localStorage
  let saved = null;
  try { saved = localStorage.getItem('tf-lang'); } catch (e) {}
  applyLang(saved === 'zh' || saved === 'en' ? saved : 'en');
})();
